-- Обмен конспектами: ссылка на сохранённый конспект.
--
-- Решение автора (23.09.2026): конспектом можно поделиться с кем угодно,
-- без согласий и регистраций — человек и так может скопировать текст и
-- переслать его, усложнять ему жизнь незачем. Ссылка — случайный ключ, а не
-- номер строки: номера идут подряд, и перебором читались бы чужие конспекты.
-- Отозвать ссылку — обнулить ключ; копии, которые получатели уже сохранили
-- себе, остаются у них, как осталась бы пересланная переписка.
ALTER TABLE notes ADD COLUMN share_token TEXT;
ALTER TABLE notes ADD COLUMN shared_at   TIMESTAMPTZ;
-- Откуда конспект пришёл, если его сохранили по ссылке: справочно, чтобы
-- не сохранять один и тот же дважды. Не внешний ключ: автор может удалить
-- свой конспект, копия от этого не пропадает.
ALTER TABLE notes ADD COLUMN copied_from BIGINT;
CREATE UNIQUE INDEX notes_share_idx ON notes (share_token) WHERE share_token IS NOT NULL;
